"""Write src/catalogue_questions.zig, the --infer rules that ask about each catalogue family no
deterministic rule detects, from catalogue/questions.json.

Each entry names its catalogue family, the yes/no question asked about each function (or file, or
the project's build and CI files), the finding's message and fix, and its severity. A family a
rule in src/rules.zig detects is not asked about: `zig build test` fails until the two agree.

    python3 catalogue/questions.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS = ROOT / "catalogue" / "questions.json"
OUT = ROOT / "src" / "catalogue_questions.zig"
SEVERITY = {"error": '@"error"', "warning": "warning", "info": "information"}
ASKS = {"function": "function", "file": "file", "project": "project"}


def zig_string(text: str) -> str:
    assert "\n" not in text, f"a question or message spans lines: {text[:60]!r}"
    assert text.strip() == text, f"trim the spaces around {text[:60]!r}"
    return json.dumps(text, ensure_ascii=False)


def split_message(message: str) -> tuple[str, str]:
    """The finding's summary, the first sentence, and its fix, the rest."""
    summary, _, fix = message.partition(". ")
    assert fix, f"a message needs a summary and a fix, as two sentences: {message[:80]!r}"
    assert summary[:1].isupper(), f"a summary starts with a capital, so findings read as a sentence: {summary[:60]!r}"
    return summary.rstrip("."), fix.rstrip(".") + "."


def entry(q: dict) -> str:
    assert q["severity"] in SEVERITY, f"{q['id']} has severity {q['severity']!r}; use error, warning or info"
    assert q["scope"] in ASKS, f"{q['id']} has scope {q['scope']!r}; use function, file or project"
    summary, fix = split_message(q["message"])
    fields = [
        f".name = {zig_string(q['id'].lower())}",
        f".alias = {zig_string(q['id'])}",
        f".advice = {zig_string(fix)}",
        f".severity = .{SEVERITY[q['severity']]}",
        ".tier = .default",
        f".question = {zig_string(q['question'])}",
        f".judgement = {zig_string(summary)}",
        f".asks = .{ASKS[q['scope']]}",
    ]
    return "    .{ " + ", ".join(fields) + " },"


def check_languages(questions: list[dict]) -> None:
    """A question for some languages only must be listed as not applicable by every other one in
    languages/manifest.zon, which is where zanity keeps what each language can't have."""
    manifest = (ROOT / "languages" / "manifest.zon").read_text()
    blocks = dict(re.findall(r'\.name = "([^"]+)",(.*?)(?=\.name = "|\Z)', manifest, re.S))
    assert blocks, "found no languages in languages/manifest.zon"
    for q in questions:
        for language, block in blocks.items():
            if not q.get("languages") or language in q["languages"]:
                continue
            listed = re.search(r"\.not_applicable = \.\{([^}]*)\}", block)
            names = re.findall(r'"([^"]+)"', listed.group(1)) if listed else []
            assert q["id"].lower() in names, f"{q['id']} is only for {q['languages']}; add \"{q['id'].lower()}\" to {language}'s not_applicable in languages/manifest.zon"


def render(questions: list[dict]) -> str:
    ids = [q["id"] for q in questions]
    assert len(ids) == len(set(ids)), "catalogue/questions.json lists a family twice"
    assert all(i.startswith(("CWE-", "EXT-")) for i in ids), f"each id names a catalogue family, such as CWE-89; not {[i for i in ids if not i.startswith(('CWE-', 'EXT-'))][:3]}"
    lines = [
        "//! Generated by catalogue/questions.py from catalogue/questions.json; edit those, not this.",
        "//! The --infer rules that ask about each catalogue family no deterministic rule detects.",
        'const Rule = @import("rules.zig").Rule;',
        "",
        "pub const questions = [_]Rule{",
        *(entry(q) for q in questions),
        "};",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    assert QUESTIONS.is_file(), f"{QUESTIONS} is missing; it holds the catalogue questions"
    questions = json.loads(QUESTIONS.read_text())
    assert questions, f"{QUESTIONS} lists no questions"
    check_languages(questions)
    OUT.write_text(render(questions))
    print(f"wrote {len(questions)} questions to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
